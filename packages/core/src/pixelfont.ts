export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const ADVANCE = 6; // 5 px glyph + 1 px gap

/** Width in SVG px of `text` at `scale`. */
export function pixelTextWidth(text: string, scale: number): number {
  const n = [...text].length;
  return n === 0 ? 0 : (n * ADVANCE - 1) * scale;
}

/** SVG <path> drawing `text` in pixels. (x, y) is the top-left corner. */
export function pixelText(text: string, x: number, y: number, scale: number, fill: string, extra = ''): string {
  const d: string[] = [];
  let cx = x;
  for (const raw of [...text]) {
    const ch = raw.toUpperCase();
    const rows = G[ch] ?? G[' ']!;
    rows.forEach((row, ry) => {
      for (let rx = 0; rx < GLYPH_W; rx++) {
        if (row[rx] === '#') d.push(`M${cx + rx * scale} ${y + ry * scale}h${scale}v${scale}h-${scale}z`);
      }
    });
    cx += ADVANCE * scale;
  }
  return `<path d="${d.join('')}" fill="${fill}" shape-rendering="crispEdges"${extra}/>`;
}

/** Draw a sprite (rows of chars) as one path per color. */
export function pixelSprite(rows: string[], palette: Record<string, string>, x: number, y: number, scale: number): string {
  const byColor = new Map<string, string[]>();
  rows.forEach((row, ry) => {
    [...row].forEach((ch, rx) => {
      const c = palette[ch];
      if (!c) return;
      if (!byColor.has(c)) byColor.set(c, []);
      byColor.get(c)!.push(`M${x + rx * scale} ${y + ry * scale}h${scale}v${scale}h-${scale}z`);
    });
  });
  return [...byColor].map(([c, d]) => `<path d="${d.join('')}" fill="${c}" shape-rendering="crispEdges"/>`).join('');
}
